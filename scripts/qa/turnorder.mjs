// LifeTrack turn-order QA: the draw screen, skip, the order on the board, pawn sequence, save/reload, event ownership.
//   node turnorder.mjs http://127.0.0.1:4181/ [WxH]
import { chromium } from 'playwright-core';
const [url, size = '1366x768'] = process.argv.slice(2); const [w, h] = size.split('x').map(Number);
const browser = await chromium.launch({ channel: 'msedge', headless: true });
let fails = 0; const check = (n, ok, d = '') => { if (!ok) fails++; console.log(`${ok ? 'PASS' : 'FAIL'} ${n} ${d}`); };
const page = await (await browser.newContext({ viewport: { width: w, height: h } })).newPage();
const errors = []; page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); }); page.on('pageerror', (e) => errors.push(e.message));
const btn = (re) => page.locator('button', { hasText: re }).first();
const save = () => page.evaluate(() => localStorage.getItem('lifetrack.game.v1'));
const board = () => page.evaluate(() => JSON.parse(localStorage.getItem('lifetrack.board.v1') ?? 'null'));
await page.goto(url); await btn(/Play the game/).click();
await page.locator('button.character-option').nth(2).click(); await btn(/^Continue/).click(); await btn(/Begin month one/).click();
await page.locator('.turn-draw').waitFor();
const s0 = await save();
check('draw screen shows four seats', (await page.locator('.td-seat').count()) === 4);
await page.waitForTimeout(1500);
check('cards are revealed progressively (not all at once)', (await page.locator('.td-seat.is-revealed').count()) < 4);
await page.locator('.td-skip').click();
const nums = await page.locator('.td-front strong').allTextContents();
check('four unique positions 1-4', [...nums].sort().join() === '1,2,3,4', nums.join());
check('skipping does not change the saved game', (await save()) === s0);
const drawn = await page.evaluate(() => [...document.querySelectorAll('.td-seat')].map((li) => ({ id: [...li.querySelector('.td-player img, .td-player [role=img]')?.getAttribute('alt') ?? ''].join(''), n: Number(li.querySelector('.td-front strong')?.textContent) })));
await page.locator('.td-start').click();
await btn(/Collect monthly income/).waitFor();
check('starting does not change the saved game', (await save()) === s0);
const mats = await page.evaluate(() => [...document.querySelectorAll('.board-card .pd-card')].map((c) => [...c.classList].find((x) => x.startsWith('pd-') && !['pd-card', 'pd-you', 'pd-active'].includes(x))?.slice(3)));
const byName = drawn.sort((a, b) => a.n - b.n).map((d) => d.id);
console.log('drawn order', byName.join(' > '), '| mats', mats.join(' > '));
check('dashboard lists players in the drawn order', mats.length === 4);
const g = JSON.parse(s0); const human = g.humanId;
await btn(/Collect monthly income/).click(); await btn(/Pay monthly essentials/).click();
await page.getByRole('button', { name: 'Roll Dice' }).waitFor({ timeout: 30000 });
const before = (await board())?.moved ?? [];
const humanAt = mats.indexOf(human);
check('rivals before the human moved first', JSON.stringify(before) === JSON.stringify(mats.slice(0, humanAt)), `moved=${before} expected=${mats.slice(0, humanAt)}`);
await page.getByRole('button', { name: 'Roll Dice' }).click();
await page.locator('button.save-action').waitFor({ timeout: 20000 });
await page.locator('button.pass-action').click(); await page.locator('button.pass-action').click();
await page.locator('button.decision-confirm').click();
await page.locator('button.event-continue').waitFor({ timeout: 40000 });
const b1 = await board();
check('all four moved in the drawn order', JSON.stringify(b1.moved) === JSON.stringify(mats), `moved=${b1.moved}`);
check('the last mover is the last in the order', b1.lastMovement?.playerId === mats[3]);
await page.locator('button.event-continue').click(); await page.locator('.everyone-outcome').waitFor();
const g1 = JSON.parse(await save());
const shown = await page.evaluate(() => Object.fromEntries([...document.querySelectorAll('.eo-row')].map((r) => [r.dataset.player, Number(r.querySelector('.eo-paid').textContent.replace(/[^0-9]/g, ''))])));
const own = Object.fromEntries(g1.players.map((p) => [p.id, p.history.find((r) => r.round === 1)?.claim?.outOfPocket ?? 0]));
check('each player shows their own claim (from their own record)', JSON.stringify(Object.keys(own).sort().map((k) => own[k])) === JSON.stringify(Object.keys(own).sort().map((k) => shown[k])), JSON.stringify({ own, shown }));
// Reload: the saved game resumes on the board, no second draw, same order.
await page.reload(); await btn(/Continue saved game/).click();
await page.waitForTimeout(1500);
check('reload resumes without a second draw', (await page.locator('.turn-draw').count()) === 0);
const mats2 = await page.evaluate(() => [...document.querySelectorAll('.board-card .pd-card, .financial-drawer .pd-card')].slice(0, 4).map((c) => [...c.classList].find((x) => x.startsWith('pd-') && !['pd-card', 'pd-you', 'pd-active'].includes(x))?.slice(3)));
check('order unchanged after reload', mats2.join() === mats.join(), mats2.join());
check('no console errors', errors.length === 0, errors.join(' | '));
console.log(fails ? `${fails} failures` : 'ALL PASS');
await browser.close(); process.exit(fails ? 1 : 0);
